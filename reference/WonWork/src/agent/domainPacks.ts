export interface DomainPackEntry {
  /** 内容版本：内置技能条目的同步覆盖以此为准；开发阶段不逐改升号，人工拍板才升（见文件头纪律） */
  version: string
  content: string
  /**
   * 写前门控装配（2026-08-09 S1/S6 拍板）：按可逆性分级挂门——
   * hard=不可逆写（写 MES），无活跃状态任务也拦（fail-closed）；
   * soft=可逆写，有活跃状态任务时才拦（fail-open）；
   * 不在清单的写工具（run_ap/run_as/run_kitting/prepare_dataset）不挂门——
   * 它们只产候选方案不改业务事实，里程碑同步即可，挂门会把排产切成多次对账。
   */
  consult?: { hard?: string[]; soft?: string[] }
}

