import i18n from '@/i18n'

/**
 * 回答语言注记（2026-08-19 用户拍板）。
 *
 * 界面语言为英文时，动态注入一句「用英文回答」；中文默认不注入——
 * 中文 system + 中文用户消息下模型自然中文作答，无需多一句废话。
 *
 * 纪律：
 * - 模型面向文本，保持中文，不进 locale 文件（与 prompt/ 各节同口径）；
 * - 只在英文模式出现，同一语言内逐字节稳定，不破坏前缀缓存分层；
 * - 主对话 / 子代理 / pipeline（标题、压缩、审批解释等）四处统一从这里取，
 *   不要各自抄写文案。
 */
export function buildAnswerLanguageNote(): string | null {
  if (!i18n.language?.startsWith('en')) return null
  return `## 回答语言
用户界面当前为英文，你的正式产出——回答正文、标题、表格、生成的文件内容——默认一律用英文。但如果用户消息本身明确使用了其他语言（例如用中文提问），则跟随用户消息的语言回答。工具调用参数与内部思考不受此限。`
}
