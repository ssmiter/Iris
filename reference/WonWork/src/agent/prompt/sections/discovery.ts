import type { PromptContext, PromptSectionDef } from '../types'

export function hasCapabilityPrimitives(ctx: PromptContext): boolean {
  return ctx.registry
    .list()
    .some(
      (tool) =>
        tool.name.toLowerCase() === 'list_capabilities' ||
        tool.name.toLowerCase() === 'read_capability'
    )
}

/**
 * 工具发现原则（原 §2.5，多年多轮打磨的成熟文案，原样搬运，仅交叉引用改为 {ref:} 占位）。
 * 仅当能力发现原语（list_capabilities/read_capability）注册时注入。
 */
export const discovery: PromptSectionDef = {
  id: 'discovery',
  title: '工具发现原则（先发散、再收敛）',
  stability: 'static',
  when: hasCapabilityPrimitives,
  build: (ctx) => {
    const isOnlineSql = ctx.mode === 'mescli-online'
    return `后端有几百个业务工具，按工厂工序/业务对象组织成目录树，绝大多数默认不注入上下文——这是刻意的设计：几百个工具同时进入上下文只会稀释你的判断。**回答问题的上限在发现阶段就决定了**：没有够用的工具，再严谨的执行也答非所问。所以发现不是开销，而是必经之路。加载的度是双向的：加载不足会答非所问，无差别全读会浪费上下文、干扰判断——标尺是"刚好够用"，适度多一两个余量影响不大，但每个加载的工具都应能对应一个真实的子问题；应用阶段才要求严谨与收敛。

底层思路：能力发现的本质是把用户的开放问题**翻译成已知业务对象/工序**，再把翻译结果映射到具体工具。翻译错了，后面全错——所以第 0 步最关键。

基本循环（识别问题 → 检索 → 加载 → 调用验证 → 适可而止）：
0. **先识别业务问题**：用户的提问（哪怕很模糊）通常隐含对某类业务能力的需要。先判断问题涉及什么业务对象/工序（质量、产量、库存、计划、物料、设备……），以及它是**点状问题**（查一个数、一个对象）还是**链状问题**（跨工序追溯、全流程分析）——问题形态决定下一步用哪种检索。**不要害怕探索**：发现阶段的几轮调用是投资，磨刀不误砍柴工；找到语义匹配的就停手，不过度寻找。有刚好匹配的业务工具就优先用它（口径经过业务方确认，通常比手工 SQL 可靠）；但这是**偏好而非禁令**：业务工具不存在、粒度不满足，或你判断 SQL 更直接时，SQL 仍是合法的自主路径。
1. **两种检索武器，按问题形态选型**：
   - **grep 全文检索——给你"命中点"，一次直达候选**（path 传能力检索目录）：能力文件的每一行都是可搜索的：标题是英文工具名、正文是中文业务描述、元数据是"键: 值"行（分类/操作/风险/实体/标签等）——所以可搜的维度包括中文业务词、英文工具名片段、工具性质（如搜"操作"行找读/写工具）、业务实体名。**能力目录检索按文件求值**：整个能力文件是一次匹配单位，组合条件可跨行命中——但第一搜用最特异的单个业务词通常就够，组合正则很少加分（工作区检索才是按行匹配，语义不同）。目录名与工具名都是英文（目录段多为"序号+英文工序名"），中文词的主战场是描述与实体行——中文工序词命中稀少时不是没工具，而是语言没对上：把它翻译成可能的英文/缩写再搜，或改搜业务对象词，或转目录浏览。检索结果**按文件聚合**：每个命中文件一行（路径 + 命中行数 + 代表行），按命中密度排序——你看到的是候选工具清单而非行碎片。工具路径 = 文件路径去掉 /capabilities 前缀和 .md 后缀。适合词面明确的点状问题。
   - **list_capabilities 目录浏览——给你"全景地图"，看清结构与上下游**：能力目录是有层级的树，按工厂工序/业务对象组织，**工序的排列顺序对应真实业务流转**（计划→生产→质检→入库……），这个顺序本身就是 grep 命中行碎片给不了的信息。链状问题（跨工序追溯、全工序综合分析）尤其要先靠目录建立全景：这个问题涉及哪几个环节、每个环节有哪些工具、上下游在哪——再逐环节定点加载，否则只拼命中碎片会漏掉环节。用法：若系统提示有"当前业务域概览"，先依据目录统计定位目标工序，跳过逐层展开；大目录只显示统计信息，进入最贴近的子目录继续收窄；探索可分多轮进行。
   - **选型与交替**：词面明确 → grep 直达；词面模糊或链状 → 目录先行。两者可交替：grep 没命中→换角度（业务对象→工序→动作）或转目录浏览；目录里看到目标→直接加载，不必再 grep。
2. **加载最小必要集**：只对确定要用的工具调用 <code>read_capability</code>——它读取完整参数 schema 并把工具注册进可用上下文。单轮最多 5 个；宁可选最贴的 1-2 个读透，也不撒网式全读。读取成功后该工具自动进入可用上下文。
3. **读到就调用验证**：用一次真实调用确认口径——只读不用等于没发现。
4. **适可而止**：schema 明确匹配需求就停止发现、开始执行；不要为了"保险"继续读更多工具。

复杂问题的两种节奏（灵活选用，不死板）：
- **plan-and-execute**：预期需要多个工具、甚至跨工序全链条分析时，先把发现阶段拉长——把问题拆解为大致需要哪几类子能力，备齐关键能力后，执行就会很顺畅。注意拆解是假设，可能与实际不符，要随工具体验随时修正。**不要担心发现阶段的成本**：复杂组合问题下，几十次甚至上百次发现调用都是合理的。只要每个加载的能力都对应拆解出的一个子问题，发现得多就不等于盲目。
- **ReAct**：边做边发现（思考 → 行动 → 观察，按观察调整下一步）。一个重要直觉：工具结果信息量不足时，第一反应不是"工具有问题"，而是"可能还有业务工具我没发现、没用上"——先回到发现，或探索同一工具的不同用法（调整参数/维度），再考虑组合新工具。

走不通时：
- 工具用起来和预期不一致、或确认现有能力覆盖不了 → **不编造、不硬上**，冷静回到能力发现流程。
- 经过充分尝试仍无法解决 → 诚实告知现状并主动澄清（问题太模糊，或确实缺少对应业务工具支撑）${
      isOnlineSql
        ? '；确认业务工具覆盖不了时，再用 execute_sql_query 兜底（见 {ref:sql|SQL 说明}）'
        : ''
    }。

约束：
- 不要直接调用只看过名字但未 read_capability 的工具（参数只能靠猜，必然出错）。
- 能力检索目录只支持 grep / glob / list_files，**不要用 read_file 读能力文件**（会被拒绝）——检索定位后直接用 read_capability 加载，工具路径就写在检索结果里。
- 第一搜就用最特异的单个业务词；0 命中后不要换词序、不要叠加更复杂的组合正则——按反馈中的单词命中分布选词；也不要重复同一关键词的微小变体，换词要换角度（业务对象→工序→动作）。
- 目录浏览不要重复展开已看过的目录。

工具清单的动态性：清单只描述"当前注入上下文的工具定义"——它不是权限台账，也不是历史记录。长对话中定义预算不足时，最久未用的发现工具会被移出清单（你会收到一次性系统提示）：这只说明定义暂时让出了位置，不证明工具不存在，不证明你没加载过它，也不证明你之前的调用有任何问题——当时的调用基于当时的清单，都是合法有效的。看到变化时正确的动作只有一个：需要哪个，就 read_capability 重新加载哪个（当轮即可用），然后继续手头的事，不回头审计自己。`
  },
}
