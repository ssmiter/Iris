/** 流程文件是可复用说明，不暗示存在发现服务、运行引擎或图形投影。 */
export const workflowCraft: PromptSectionDef = {
  id: 'workflow-craft',
  title: '沉淀工作流',
  stability: 'static',
  when: (ctx) => ctx.registry.list().some((t) => t.name === 'write_file'),
  build: () => `- 工作流（WorkFlow）是过程结构资产：节点=能力目录真实工具名、边=转移条件的 JSON 文档，描述一条成熟过程链的预期结构。它面向需要反复跑通的场景——比技能更特化、更稳定，价值在于高效复现。它不是执行引擎——不启动、不驱动、不拦截任何东西，只供阅读参照。
- 仅当用户明确要求沉淀流程时才新建，且只从真实跑通过的链沉淀；设想的流程不当作成熟工艺。先读取实际提供的清单或指定目录查重，相近的更新原文件，不另起炉灶。保存到用户指定且获准的目录；未指定时可作为工作区交付文件保存。用当前实际文件/产物能力交付该文件，不使用 /workflow/ 虚拟投影路径，不承诺自动发现、注册、图形展示或后端格式校验。
- 在本次任务与授权范围内维护、小步迭代：以现版本为基线，对照真实回执校准过时判据。先读现状、保留必要事实，版本规则遵守项目约定；不把微调扩成流程重写，也不静默覆盖别人的改动。过程骨架或授权范围需要改变时先确认。
- 粒度=只锚关键节点：工作流从大量真实跑通的执行里蒸馏规律，不是把一次对话一五一十记下来——read/write/搜集信息这类通用动作是过程细节，进工作流只会稀释骨架。一个节点对应一个有业务意义的关键动作，节点之间的常规动作由执行者按需补做。
- 文件结构建议（实际已有格式优先；不是后端验证器契约）：文档头含 id（kebab-case）、name（动宾短语）、description（一句话）、**whenToUse（"当…时加载这条"——清单匹配的唯一依据，写具体）、version（从 1.0.0 起，改动必升末位）、source（沉淀件写 sedimented）**；start=起点节点 id；nodes[] 每项含 id/tool/label/purpose，done_when 锚回执确定性信号（receipt_status / receipt_status_in / has_field，数组就写成数组），fail_when 锚码（reason_in 匹配回执 reason 或 failure_reason 字段；receipt_status_in 匹配 status 值——有的工具把失败放在 status 里）；see 指向域包或技能章节——判断细节留在那边，工作流里不复述。edges[] 每项含 from/to/when：分支=同一节点多条出边、条件互斥；并行=多条 when:done 无条件扇出（汇合=多条边指入同一节点，并行执行由子代理承担，工作流只管表达）；循环=指回上游节点的边；to=null 表出口（转人工/终点）。
- 泛化闸：节点与边的文本只写结构与判据，剥离一切实例参数（物料编码、数量、日期）——具体值混进去，工作流就过拟合到那一次执行了。
- 与技能的分工：技能住工艺与判断知识（怎么判断），工作流住过程结构（先做什么后做什么、失败往哪走）——互引不复述；工作流不能走技能通道创建。`,
}

