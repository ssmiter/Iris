/** 历史消息 → 展示态映射（loadMessages / loadTurn / hydrateAllLightRows 共用） */
function mapHistoryMessage(m: Message): ChatMessage {
  return {
    ...m,
    id: generateId(),
    // 保留原消息时间，避免切换对话后所有历史消息都变成当前时间戳。
    // 优先级（2026-08-05 精度修复）：extras 往返的客户端毫秒 ts（clientTs）
    // > 写穿缓存里原始消息的 timestamp > 后端秒级 createdAt > 现在。
    timestamp:
      typeof (m as any).clientTs === 'number'
        ? (m as any).clientTs
        : typeof (m as any).timestamp === 'number'
          ? (m as any).timestamp
          : (m as any).createdAt
            ? new Date((m as any).createdAt).getTime()
            : Date.now(),
    content: m.content,
  }
}

/** 轻行丢失 isSupplement（extras 已剥）：user 轻行与前行同轮即补充消息，补回标记防误开新轮 */
function deriveLightSupplements(messages: ChatMessage[]): ChatMessage[] {
  for (let i = 1; i < messages.length; i++) {
    const m = messages[i]
    if (m.light && m.role === 'user' && m.turnIndex != null && m.turnIndex === messages[i - 1].turnIndex) {
      m.isSupplement = true
    }
  }
  return messages
}

